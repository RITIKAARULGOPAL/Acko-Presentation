"""Build data/plan-hover-data.js (plan + room and team hovers) from the test-fit DXFs.

usage:
    python tools/plan_hover/build_plan_hover.py --op1 "Testfit OP1 - 09.10.26.dxf" --op2 "Test Fit op2 09.10.2026.dxf"
           [--op3 "Testfit -14.10.26 combined.dxf"] [--out data/plan-hover-data.js] [--keep work_dir]

Option 03 is the CAD team's two 15.10 files of the 14.10 test fit, combined by tools/plan_hover/combine_1410.py.
For each option it runs, in order:
    recreate.py  -> the plan as SVG (instanced: repeated blocks written once)
    rooms.py     -> room outlines (MI_ room layers, walls as fallback)
    teams.py     -> team zones and their seats (MI_ team zones + hatches)
    rooms.py     -> again, so corridors are cut back around the team furniture
and packs the results into one script file that works offline (loaded with a <script> tag, no fetch).
"""
import argparse, json, os, re, subprocess, sys, tempfile, time

HERE = os.path.dirname(os.path.abspath(__file__))


def run(script, dxf, out):
    t = time.time()
    r = subprocess.run([sys.executable, os.path.join(HERE, script), dxf, out], capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout[-2000:] + r.stderr[-4000:])
        raise SystemExit(f"{script} failed on {dxf}")
    print(f"    {script:12s} {time.time() - t:5.1f}s")


def build_option(dxf, work):
    os.makedirs(work, exist_ok=True)
    for script in ("recreate.py", "rooms.py", "teams.py", "rooms.py"):
        run(script, dxf, work)
    head = open(os.path.join(work, "full.svg"), encoding="utf-8").read(600)
    view_box = re.search(r'viewBox="([^"]+)"', head).group(1)
    rooms = json.load(open(os.path.join(work, "rooms.json"), encoding="utf-8"))
    teams = json.load(open(os.path.join(work, "teams.json"), encoding="utf-8"))
    metrics = json.load(open(os.path.join(work, "metrics.json"), encoding="utf-8"))
    return dict(
        source=os.path.basename(dxf),
        viewBox=view_box,
        svg=open(os.path.join(work, "instanced.svg"), encoding="utf-8").read(),
        rooms=[{k: s[k] for k in ("id", "name", "m2", "x", "y", "d")} for s in rooms["spaces"]],
        teams=[{k: t.get(k) for k in ("id", "name", "pax", "seats", "hot_desks", "x", "y", "zone", "desks")}
               for t in teams["teams"]],
        accuracy_mm=metrics["instanced"]["dev_mm"]["p100"],
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--op1", required=True)
    ap.add_argument("--op2", required=True)
    ap.add_argument("--op3", help="the 14.10 test fit")
    ap.add_argument("--out", default="data/plan-hover-data.js")
    ap.add_argument("--keep", help="keep the intermediate files (SVGs, JSON, debug PNGs) in this folder")
    a = ap.parse_args()
    work_root = a.keep or tempfile.mkdtemp(prefix="plan_hover_")
    data = {"built": time.strftime("%Y-%m-%d %H:%M"), "options": {}}
    for key, dxf in (("op1", a.op1), ("op2", a.op2), ("op3", a.op3)):
        if not dxf:
            continue
        print(f"  {key}: {dxf}")
        data["options"][key] = build_option(os.path.abspath(dxf), os.path.join(work_root, key))
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("/* generated by tools/plan_hover/build_plan_hover.py - do not hand-edit */\n")
        f.write("window.PLAN_HOVER = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print(f"wrote {a.out} ({os.path.getsize(a.out) / 1e6:.1f} MB)")
    for key, o in data["options"].items():
        print(f"  {key}: {len(o['rooms'])} rooms, " + ", ".join(f"{t['name']} {t['seats']}/{t['pax']}" for t in o["teams"]))


if __name__ == "__main__":
    main()
