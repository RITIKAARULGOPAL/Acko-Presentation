"""Site context for the twin: Sattva Hallmark in its street, the metro viaduct,
and the façade data the glazing shader needs.

Reads the site bundle produced by site-context/axo/build_axo_data.py (OSM context,
the two Hallmark blocks traced from satellite, the plan placement) and writes

  data/site-data.js      window.MX_SITE  -- geometry in TWIN coordinates

Twin frame: x = (plan_x - 42000) / 1000, z = -(plan_y - 17500) / 1000, y up,
Level 03 slab top at y = 0, so the ground sits at y = -slab height.

usage: python tools/build_site.py [--axo <path to axo_data.js>]
       python tools/build_site.py --soc-only     (refresh the SOC runs from data/zones.json after a layout change)
"""
import os, sys, json, math
from PIL import Image
from shapely.geometry import Polygon, LineString, Point
from shapely.ops import unary_union
import random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args = sys.argv[1:]
CX, CY = 42000, 17500


def soc_runs(blocks, zones):
    """SOC glazing runs: where each option's SOC zone meets the east block's façade (Level 03 only)"""
    east = next(bl for bl in blocks if bl["mitigata"])
    soc = {}
    for o in ("opt1", "opt2"):
        runs = []
        for z in zones[o]["zones"]:
            if z["type"] != "soc":
                continue
            zp = Polygon([[round((x - CX) / 1000, 3), round(-(y - CY) / 1000, 3)] for x, y in z["poly"]]).buffer(2.0)   # zones stop ~1.6 m inside the façade line
            for i, fa in enumerate(east["facades"]):
                seg = LineString([fa["a"], fa["b"]])
                hit = seg.intersection(zp)
                if hit.is_empty or hit.length < 2:
                    continue
                for g in getattr(hit, "geoms", [hit]):
                    us = [seg.project(Point(p)) for p in g.coords]
                    runs.append({"edge": i, "u0": round(min(us), 2), "u1": round(max(us), 2)})
        soc[o] = runs
        print(o, "SOC glazing runs", [(r["edge"], round(r["u1"] - r["u0"], 1)) for r in runs])
    return soc


# --soc-only: refresh just the SOC glazing runs from today's data/zones.json (after a layout change),
# keeping the rest of data/site-data.js -- the full build needs site-context/axo/axo_data.js
if "--soc-only" in args:
    path = os.path.join(ROOT, "data", "site-data.js")
    txt = open(path, encoding="utf-8").read()
    M = json.loads(txt[txt.index("{"):txt.rindex("}") + 1])
    M["soc"] = soc_runs(M["blocks"], json.load(open(os.path.join(ROOT, "data", "zones.json"), encoding="utf-8")))
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("/* site context for the twin -- generated by tools/build_site.py, don't hand-edit */\n")
        fh.write("window.MX_SITE=" + json.dumps(M, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print("refreshed the SOC runs in data/site-data.js")
    sys.exit(0)
AXO = args[args.index("--axo") + 1] if "--axo" in args else os.path.join(os.path.dirname(ROOT), "site-context", "axo", "axo_data.js")
IMG = os.path.join(ROOT, "assets", "img")

src = open(AXO, encoding="utf-8").read()
A = json.loads(src[src.index("{"):src.rindex("}") + 1])
S, P = A["site"], A["plan"]
slabZ = S["level"] * S["ftf"]

# site metres -> plan mm -> twin
a, b, c, d, e, f = P["T"]
det = a * e - b * d
def to_plan(E, N):
    x, y = E - c, N - f
    return ((e * x - b * y) / det, (-d * x + a * y) / det)
def tw(E, N):
    px, py = to_plan(E, N)
    return [round((px - CX) / 1000, 2), round(-(py - CY) / 1000, 2)]
def ring(r):
    return [tw(*p) for p in r]
def poly_list(polys):
    return [[ring(r) for r in rings] for rings in polys]

# ---- façades: perimeter edges of both blocks, with SOC runs per option ----
def facades(r_site):
    pts = ring(r_site)
    P_ = Polygon(pts)
    if P_.exterior.is_ccw:            # want clockwise in (x, z) so outward = right-hand normal
        pts = pts[::-1]
    out = []
    for i in range(len(pts)):
        (ax, az), (bx, bz) = pts[i], pts[(i + 1) % len(pts)]
        L = math.hypot(bx - ax, bz - az)
        if L < 1:
            continue
        tx, tz = (bx - ax) / L, (bz - az) / L
        nx, nz = -tz, tx
        # make sure the normal points out of the block
        mx_, mz_ = (ax + bx) / 2 + nx * 0.5, (az + bz) / 2 + nz * 0.5
        if P_.contains(Point(mx_, mz_)):
            nx, nz = -nx, -nz
        out.append({"a": [ax, az], "b": [bx, bz], "n": [round(nx, 4), round(nz, 4)], "len": round(L, 2)})
    return out

blocks = []
for bl in S["blocks"]:
    parts = [{"ring": ring(p["ring"]), "h": p["h"]} for p in bl["parts"]]
    blocks.append({"name": bl["name"], "mitigata": bool(bl.get("mitigata")), "ring": ring(bl["ring"]),
                   "parts": parts, "h": max(p["h"] for p in bl["parts"]), "facades": facades(bl["ring"])})

soc = soc_runs(blocks, json.load(open(os.path.join(ROOT, "data", "zones.json"), encoding="utf-8")))

# ---- street trees, traced from the satellite still (OSM has none here) ----
# sat_z19 is a 1920x1080 capture at zoom 19 centred on the pin (tools/capture_sat.js);
# canopy = green pixels, sampled on a 3 m grid, building footprints excluded.
import numpy as np
SAT_LAT, SAT_LNG, SAT_Z = 12.9366189, 77.6916687, 19
LAT0, LON0 = 12.93656, 77.69169                       # site origin (site-context/build_context.py)
phi = math.radians(LAT0)
M_LAT = 111132.92 - 559.82 * math.cos(2 * phi) + 1.175 * math.cos(4 * phi)
M_LON = 111412.84 * math.cos(phi) - 93.5 * math.cos(3 * phi)
mpp = 156543.03392 * math.cos(math.radians(SAT_LAT)) / 2 ** SAT_Z
cE, cN = (SAT_LNG - LON0) * M_LON, (SAT_LAT - LAT0) * M_LAT
sat = np.asarray(Image.open(os.path.join(ROOT, "assets", "site", "sat_z19.webp")).convert("RGB")).astype(int)
r_, g_, b_ = sat[..., 0], sat[..., 1], sat[..., 2]
exg = 2 * g_ - r_ - b_                                  # excess-green index: holds up in shadowed foliage
canopy = (exg > 14) & (g_ > 28) & (g_ < 175) & (g_ > r_)
foot = unary_union([Polygon(bd["r"]).buffer(1.5) for bd in A["buildings"]] + [Polygon(bl["ring"]).buffer(1.5) for bl in S["blocks"]]
                   + [Polygon(S["atrium"]["ring"]), Polygon(S["canopy"]["ring"])])
# canopy fraction on a 1 m grid in the site frame (integral image for the box sums)
TREE_R, CELL = 170, 1.0
ii = np.pad(canopy.astype(np.float32).cumsum(0).cumsum(1), ((1, 0), (1, 0)))
def frac(E, N, half):
    px, py = 960 + (E - cE) / mpp, 540 - (N - cN) / mpp
    h = half / mpp
    x0, x1 = int(max(0, px - h)), int(min(sat.shape[1], px + h))
    y0, y1 = int(max(0, py - h)), int(min(sat.shape[0], py + h))
    if x1 <= x0 or y1 <= y0:
        return 0.0
    return float(ii[y1, x1] - ii[y0, x1] - ii[y1, x0] + ii[y0, x0]) / ((x1 - x0) * (y1 - y0))
n = int(2 * TREE_R / CELL)
Es = -TREE_R + (np.arange(n) + 0.5) * CELL
F = np.array([[frac(E, N, 2.0) for E in Es] for N in Es])           # 4 m box: crown-sized smoothing
blocked = np.array([[math.hypot(E, N) > TREE_R or foot.contains(Point(E, N)) for E in Es] for N in Es])
F[blocked] = 0
# greedy crowns: take the densest cell, grow the largest disc that is still mostly canopy, suppress it
trees_site, used = [], np.zeros_like(F, bool)
order = np.dstack(np.unravel_index(np.argsort(-F, axis=None), F.shape))[0]
for iy, ix in order:
    if F[iy, ix] < 0.62:
        break
    if used[iy, ix]:
        continue
    E, N = Es[ix], Es[iy]
    r = 1.5
    while r < 7.5 and frac(E, N, (r + 0.5) * 0.89) > 0.55:   # box of equal area to the disc
        r += 0.5
    trees_site.append((E, N, r))
    k = int(math.ceil(r * 0.85 / CELL))
    yy, xx = np.ogrid[-k:k + 1, -k:k + 1]
    m = (xx ** 2 + yy ** 2) <= k * k
    y0, x0 = iy - k, ix - k
    sl = (slice(max(0, y0), iy + k + 1), slice(max(0, x0), ix + k + 1))
    used[sl] |= m[(max(0, y0) - y0):(m.shape[0] - max(0, iy + k + 1 - n)), (max(0, x0) - x0):(m.shape[1] - max(0, ix + k + 1 - n))]

# the forecourt: the gap in the service-road façade between the two blocks' prows
west_r, east_r = S["blocks"][1]["ring"], S["blocks"][0]["ring"]
if S["blocks"][0].get("mitigata") is not True:
    west_r, east_r = east_r, west_r
cr = S["canopy"]["ring"]                     # [west block SE-arm end, east apex, east SW-arm end, west edge]
m0, m1 = cr[0], cr[1]
dx_, dy_ = m1[0] - m0[0], m1[1] - m0[1]; L_ = math.hypot(dx_, dy_); ux, uy = dx_ / L_, dy_ / L_
nx_, ny_ = uy, -ux                           # pick the normal that points away from the buildings (to the road)
bc = Polygon(east_r).centroid
if (bc.x - (m0[0] + m1[0]) / 2) * nx_ + (bc.y - (m0[1] + m1[1]) / 2) * ny_ > 0:
    nx_, ny_ = -nx_, -ny_
mid = ((m0[0] + m1[0]) / 2, (m0[1] + m1[1]) / 2)
island = (mid[0] + nx_ * 9, mid[1] + ny_ * 9)
rnd_ = random.Random(7)
# street trees here stand 10-15 m apart (Street View, Apr 2026): merged canopy strips on the satellite
# must not become forests -- keep the biggest crowns first, at least ~8 m apart, crowns capped at 5 m
MAX_R, MIN_GAP = 5.0, 8.0
kept = []
for E, N, r in sorted(trees_site, key=lambda t: -t[2]):
    r = min(r, MAX_R)
    if all(math.hypot(E - e, N - n) >= max(MIN_GAP, 0.9 * (r + rk)) for e, n, rk in kept):
        kept.append((E, N, r))

# the ORR separator (between the service road and the main carriageway, beside the metro): a row of fan
# palms (Street View, Apr 2026). On the satellite its crowns sit 9-12 m from the viaduct's centreline on the
# site side, so the row runs at 10.3 m: palm-sized crowns there become palms, gaps get one every ~12 m
deck = unary_union([Polygon(pp[0]) for pp in A["viaduct"]["deck"]])
mrr = list(deck.minimum_rotated_rectangle.exterior.coords)
long_edges = sorted([(mrr[i], mrr[i + 1]) for i in range(4)], key=lambda ab: -math.dist(*ab))[:2]
(p0, p1), (q0, q1) = long_edges
cl0, cl1 = ((p0[0] + q1[0]) / 2, (p0[1] + q1[1]) / 2), ((p1[0] + q0[0]) / 2, (p1[1] + q0[1]) / 2)
vx, vy = cl1[0] - cl0[0], cl1[1] - cl0[1]; vl = math.hypot(vx, vy); vx, vy = vx / vl, vy / vl
side = 1 if (vx * (0 - cl0[1]) - vy * (0 - cl0[0])) > 0 else -1          # the site's side of the viaduct
sep_n = (-vy * side, vx * side)
def sep_dist(E, N):                                                          # signed: + towards the site
    return (E - cl0[0]) * sep_n[0] + (N - cl0[1]) * sep_n[1]
SEP = 10.3
t0 = (0 - cl0[0]) * vx + (0 - cl0[1]) * vy                                   # the site point, along the viaduct
median_palms, keep_broad = [], []
for E, N, r in kept:
    if abs(sep_dist(E, N) - SEP) < 2.2 and r <= 3.6: median_palms.append((E, N))
    else: keep_broad.append((E, N, r))
kept = keep_broad
for t in np.arange(t0 - 160, t0 + 160, 12.0):
    E, N = cl0[0] + vx * t + sep_n[0] * SEP, cl0[1] + vy * t + sep_n[1] * SEP
    if math.hypot(E, N) > TREE_R: continue
    if all(math.hypot(E - x, N - y) > 7 for x, y in median_palms) and all(math.hypot(E - x, N - y) > 5 for x, y, _ in kept):
        median_palms.append((E, N))

trees = []
for E, N, r in kept:
    palm = math.hypot(E - island[0], N - island[1]) < 17
    h = (rnd_.uniform(8, 11) if palm else min(13, max(5.5, 1.4 * r + rnd_.uniform(3, 5))))
    trees.append(tw(E, N) + [round(r if not palm else min(r, 3.2), 1), round(h, 1), 1 if palm else 0])
for E, N in median_palms:
    trees.append(tw(E, N) + [2.8, round(rnd_.uniform(10, 12.5), 1), 1])
print(f"trees: {len(trees)} ({sum(t[4] for t in trees)} palms, {len(median_palms)} on the ORR median)")
# boundary hedge + railing: along the façade line, from the west prow to the east block's SE corner, 5 m out
hw0, hw1 = west_r[0], east_r[1]
hedge = [tw(hw0[0] + nx_ * 5, hw0[1] + ny_ * 5), tw(mid[0] + nx_ * 5 - ux * 6, mid[1] + ny_ * 5 - uy * 6),
         None, tw(mid[0] + nx_ * 5 + ux * 9, mid[1] + ny_ * 5 + uy * 9), tw(hw1[0] + nx_ * 5, hw1[1] + ny_ * 5)]
gate = {"island": tw(*island), "kiosk": tw(island[0] + ux * 8 + nx_ * 3, island[1] + uy * 8 + ny_ * 3),
        "barrier": [tw(island[0] + ux * 6.5 + nx_ * 3, island[1] + uy * 6.5 + ny_ * 3), tw(island[0] + ux * 1 + nx_ * 3, island[1] + uy * 1 + ny_ * 3)],
        "hedge": [hedge[:2], hedge[3:]],
        }

V = A["viaduct"]
site = {
    "slabZ": slabZ, "ftf": S["ftf"], "level": S["level"], "R": A["R"],
    "centre": tw(0, 0),
    "buildings": [{"r": ring(bd["r"]), "h": bd["h"]} for bd in A["buildings"]],
    "blocks": blocks, "soc": soc,
    "atrium": {"ring": ring(S["atrium"]["ring"]), "h": S["atrium"]["h"]},
    "canopy": {"ring": ring(S["canopy"]["ring"]), "z": S["canopy"]["z"]},
    "roads": {k: poly_list(v) for k, v in A["roads"].items()},
    "green": poly_list(A["green"]), "water": poly_list(A["water"]),
    "trees": trees,                       # [x, z, crown radius, height, palm?] in twin coords
    "gate": gate,                         # forecourt island, kiosk, boom barrier, boundary hedge

    "viaduct": {k: V[k] for k in ("deck_bottom", "deck_top", "parapet", "half_width", "pier_r")} |
               {"deck": poly_list(V["deck"])},
    "credit": "Context © OpenStreetMap contributors (ODbL) · footprints traced from Google imagery",
}
# a site-frame heading -> three.js rotation.y in the twin (local +x along the heading)
def heading(x, y, ang):
    p0, p1 = tw(x, y), tw(x + math.cos(ang), y + math.sin(ang))
    return round(math.atan2(-(p1[1] - p0[1]), p1[0] - p0[0]), 4)
site["viaduct"]["piers"] = [tw(x, y) + [heading(x, y, ang)] for x, y, ang in V["piers"]]
site["north"] = heading(0, 0, math.pi / 2)

with open(os.path.join(ROOT, "data", "site-data.js"), "w", encoding="utf-8") as fh:
    fh.write("/* site context for the twin -- generated by tools/build_site.py, don't hand-edit */\n")
    fh.write("window.MX_SITE=" + json.dumps(site, separators=(",", ":"), ensure_ascii=False) + ";\n")

for fn in ("site-data.js",):
    print(f"wrote data/{fn} {os.path.getsize(os.path.join(ROOT, 'data', fn)) / 1e6:.2f} MB")
