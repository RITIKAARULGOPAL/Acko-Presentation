"""The site and the bare floor for the short site, sun and fire beats, from the earlier Acko analysis (Acko New 01: test fit 03,
the same floor and shell; the site from Overture/OSM, the sun from NOAA formulas). Reads the RF and SITE blocks that deck
embedded, as saved by the one-off extraction into tools/_media/RF.json and SITE.json, and writes data/site-floor.js
(window.ACKO_SITE, window.ACKO_FLOOR).

    python tools/acko/site_floor.py
When the new layout DXF arrives, the floor part is regenerated from it instead (the shell, stairs and cores don't change).
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
rf = json.load(open(os.path.join(ROOT, "tools", "_media", "RF.json")))
st = json.load(open(os.path.join(ROOT, "tools", "_media", "SITE.json")))

r1 = lambda v: round(v, 1)
pts = lambda a: [[r1(p[0]), r1(p[1])] for p in a]

floor = {
    "unit": rf["unit"], "len": rf["len"], "depth": rf["depth"], "m2": rf["plateM2"], "daylight": rf["daylight"],
    "plate": pts(rf["plate"]), "terraces": [pts(t) for t in rf["terraces"]], "cutout": pts(rf["cutout"]),
    "stairs": [{k: s[k] for k in ("id", "x", "y", "w", "h")} for s in rf["stairs"]],
    "lifts": [{k: l[k] for k in ("x", "y", "w", "h")} for l in rf["lifts"]],
    "cols": [[c[0], c[1], c[2], c[3]] for c in rf["cols"]],
    "cores": [pts(p) for it in rf["dd"]["items"] if it["k"] in ("lobby", "wash", "stair", "ahu") for p in it["polys"]],
    "entries": rf["dd"].get("entries"), "comp": rf["dd"].get("comp"),
    "routes": [{"pts": pts(r["pts"]), "m": r["m"], "to": r["to"]} for r in rf["routes"]],
    "sun": [{"k": d["k"], "label": d["label"], "frames": [{"t": f["t"], "az": f["az"], "alt": f["alt"], "p": [p["d"] for p in f.get("p", [])]} for f in d["frames"]]} for d in st["sun"]["day"]],
}
site = {
    "grid": st["gridDeg"], "frame": st["frame"], "footprint": st["footprint"], "gate": st["gate"], "onSite": st["onSite"],
    "hosur": st["hosur"], "buildings": [b[0] for b in st["buildings"]],
    "roads": [{"c": r["c"], "w": r["w"], "rank": r["rank"], "d": r["d"]} for r in st["roads"]],
    "rail": st.get("rail"), "land": st.get("land"), "water": st.get("water"),
    "labels": [l for l in st["labels"] if l.get("rank", 9) <= 1],
    "marks": st["marks"], "facts": {k: st["facts"][k] for k in ("building", "floor", "sbaSft", "carpetSft", "headcount")},
    "attribution": st["attribution"],
}
with open(os.path.join(ROOT, "data", "site-floor.js"), "w", encoding="utf8") as f:
    f.write("/* generated by tools/acko/site_floor.py: the site (Overture/OSM) and the bare floor (test fit 03 shell), from the earlier Acko analysis */\n")
    f.write("window.ACKO_SITE = " + json.dumps(site, separators=(",", ":")) + ";\n")
    f.write("window.ACKO_FLOOR = " + json.dumps(floor, separators=(",", ":")) + ";\n")
print(os.path.getsize(os.path.join(ROOT, "data", "site-floor.js")) // 1024, "KB;", len(site["buildings"]), "buildings;", sum(len(d["frames"]) for d in floor["sun"]), "sun frames")
print("comp", json.dumps(floor["comp"])[:300]); print("entries", json.dumps(floor["entries"])[:200])
print("land", json.dumps(site["land"])[:200]); print("water", json.dumps(site["water"])[:120]); print("rail", json.dumps(site["rail"])[:120])
print("labels", [l["t"] for l in site["labels"]])
